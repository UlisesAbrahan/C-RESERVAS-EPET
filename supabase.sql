create table if not exists public.configuracion (
  clave text primary key,
  valor text not null
);

insert into public.configuracion (clave, valor)
values ('cantidad_pc', '30')
on conflict (clave) do nothing;

create table if not exists public.reservas (
  id bigint generated by default as identity primary key,
  fecha date not null,
  hora_inicio time not null,
  hora_fin time not null,
  profesor text not null,
  curso text not null,
  cantidad_pc integer not null check (cantidad_pc > 0),
  observaciones text,
  creado_en timestamptz not null default now(),
  constraint horario_valido check (hora_fin > hora_inicio)
);

-- Seguridad: activar RLS.
alter table public.configuracion enable row level security;
alter table public.reservas enable row level security;

-- Los visitantes pueden consultar configuración y reservas.
drop policy if exists "public_read_configuracion" on public.configuracion;
create policy "public_read_configuracion"
on public.configuracion for select
to anon, authenticated
using (true);

drop policy if exists "public_read_reservas" on public.reservas;
create policy "public_read_reservas"
on public.reservas for select
to anon, authenticated
using (true);

-- Los visitantes pueden crear reservas.
-- Reglas: no se permiten fechas pasadas (respecto a "hoy" en el servidor)
-- ni fechas de sábado o domingo (extract(dow): 0 = domingo, 6 = sábado).
drop policy if exists "public_insert_reservas" on public.reservas;
create policy "public_insert_reservas"
on public.reservas for insert
to anon, authenticated
with check (
  length(trim(profesor)) between 2 and 80
  and length(trim(curso)) between 1 and 40
  and cantidad_pc between 1 and 40
  and hora_fin > hora_inicio
  and fecha >= current_date
  and extract(dow from fecha) not in (0, 6)
);

-- Función de seguridad: comprueba que una nueva reserva no supere
-- la cantidad de computadoras disponibles en ningún momento.
create or replace function public.verificar_capacidad_reserva()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  capacidad integer;
  max_usadas integer;
  punto time;
begin
  if new.fecha < current_date then
    raise exception 'FECHA_PASADA';
  end if;

  if extract(dow from new.fecha) in (0, 6) then
    raise exception 'FIN_DE_SEMANA';
  end if;

  select valor::integer into capacidad
  from public.configuracion
  where clave = 'cantidad_pc';

  if capacidad is null then
    raise exception 'CAPACIDAD_NO_CONFIGURADA';
  end if;

  if new.cantidad_pc > capacidad then
    raise exception 'CAPACIDAD_INSUFICIENTE';
  end if;

  -- Revisa cada inicio/fin de reserva existente que pueda cambiar
  -- la cantidad simultánea durante el intervalo nuevo.
  for punto in
    select distinct x
    from (
      select hora_inicio as x from public.reservas
      where fecha = new.fecha
        and hora_inicio < new.hora_fin
        and hora_fin > new.hora_inicio
      union
      select hora_fin as x from public.reservas
      where fecha = new.fecha
        and hora_inicio < new.hora_fin
        and hora_fin > new.hora_inicio
      union
      select new.hora_inicio
      union
      select new.hora_fin
    ) q
    order by x
  loop
    select coalesce(sum(cantidad_pc),0) + new.cantidad_pc
    into max_usadas
    from public.reservas
    where fecha = new.fecha
      and hora_inicio <= punto
      and hora_fin > punto;

    if max_usadas > capacidad then
      raise exception 'CAPACIDAD_INSUFICIENTE';
    end if;
  end loop;

  return new;
end;
$$;

drop trigger if exists trigger_verificar_capacidad on public.reservas;
create trigger trigger_verificar_capacidad
before insert on public.reservas
for each row
execute function public.verificar_capacidad_reserva();

-- =========================================================
-- ADMINISTRADORES
-- Cada fila identifica un usuario de Supabase Auth que puede
-- administrar (eliminar) reservas.
-- Después de crear el usuario administrador en Authentication,
-- insertá su UUID en esta tabla.
-- =========================================================
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.admin_users enable row level security;

drop policy if exists "admin_users_self_read" on public.admin_users;
create policy "admin_users_self_read"
on public.admin_users for select
to authenticated
using (user_id = auth.uid());

-- Solo un usuario registrado en admin_users puede eliminar reservas.
drop policy if exists "admin_delete_reservas" on public.reservas;
create policy "admin_delete_reservas"
on public.reservas for delete
to authenticated
using (
  exists (
    select 1
    from public.admin_users a
    where a.user_id = auth.uid()
  )
);

-- Permisos mínimos para la aplicación pública.
grant select on public.configuracion to anon, authenticated;
grant select, insert, delete on public.reservas to anon, authenticated;
grant select on public.admin_users to authenticated;
grant usage, select on sequence public.reservas_id_seq to anon, authenticated;
